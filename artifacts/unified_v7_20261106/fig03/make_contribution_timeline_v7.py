#!/usr/bin/env python3
"""Render the module-level contribution timeline from the classification ledger (V7 house style).

Copy of scripts/make_contribution_timeline.py. The counting, dating, fitting, period shares and lead detection
are unchanged; only the presentation follows the V7 kit (Comic Sans MS, HUE dark colours per layer, Title Case,
kit point sizes on a 13.333 in canvas, soft grid, tinted dashed panels with dark pill titles). Outputs go to this
folder only: Figure03_V7.pdf/.png, module_contribution_timeline.csv and the coverage JSON.
"""

from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

import matplotlib.pyplot as plt
import matplotlib.dates as mdates
import matplotlib.patheffects as pe
from matplotlib.patches import FancyBboxPatch
from datetime import datetime, timedelta

import numpy as np
from scipy.optimize import curve_fit


HERE = Path(__file__).resolve().parent
ROOT = Path(__file__).resolve().parents[3]
LEDGER = ROOT / "paper_classification_ledger.json"
OUT_PNG = HERE / "Figure03_V7.png"
OUT_PDF = HERE / "Figure03_V7.pdf"
OUT_CSV = HERE / "module_contribution_timeline.csv"
OUT_COVERAGE = HERE / "module_contribution_timeline_coverage.json"


def count_module_labels(value: dict) -> int:
    """Count concrete module labels in one exclusive ledger view.

    ``module_level_contributions`` is generated by the classification manager
    after applying the deepest-applicable-layer rule. Counting its labels
    keeps the plot at module level without promoting a task-bound component
    back into GTS or GH.
    """
    dimensions = value.get("dimensions", value) if isinstance(value, dict) else {}
    return len({label for labels in dimensions.values() if isinstance(labels, list) for label in labels})


def contribution_counts(record: dict) -> dict[str, int]:
    module = record.get("module_level_contributions", {})
    if "modules" in module and module.get("review_status") in {"paper_verified", "repository_verified"}:
        counts = Counter(m["layer"] for m in module["modules"])
        return {"LLM-side": counts["LLM"], "General Harness": counts["GH"],
                "General Time Series Harness": counts["GTS"], "Task-Specific Harness": counts["TSK"]}
    return {name: 0 for name in ("LLM-side", "General Harness", "General Time Series Harness", "Task-Specific Harness")}


def main() -> None:
    records = json.loads(LEDGER.read_text(encoding="utf-8"))
    monthly: dict[str, Counter] = {}
    dated_records, undated = [], []
    for record in records:
        counts = contribution_counts(record)
        if not sum(counts.values()):
            continue
        month = record.get("publication", {}).get("public_month")
        if not month:
            first = record.get("publication", {}).get("first_public_date") or ""
            if len(first) == 4 and first.isdigit():
                month = first
        if month and len(month) == 4 and month.isdigit():
            # Year-only records are plotted at January and remain marked as
            # year precision in the ledger; this keeps them visible without
            # inventing a month in the source metadata.
            month = f"{month}-01"
        if month and not (len(month) == 7 and month[4] == "-" and month[:4].isdigit() and month[5:].isdigit()):
            year = record.get("publication", {}).get("first_public_date")
            month = f"{year}-01" if year and len(year) == 4 and year.isdigit() else None
        if not month:
            undated.append(record["citation"]["key"])
            continue
        dated_records.append(record["citation"]["key"])
        monthly.setdefault(month, Counter()).update(counts)

    months = sorted(monthly)
    running = Counter()
    rows = []
    cumulative = {name: [] for name in contribution_counts(records[0])}
    for month in months:
        running.update(monthly[month])
        row = {"public_month": month}
        for name in cumulative:
            cumulative[name].append(running[name])
            row[name] = running[name]
        rows.append(row)

    OUT_CSV.write_text("", encoding="utf-8")
    with OUT_CSV.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["public_month", *cumulative], lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)

    OUT_COVERAGE.write_text(json.dumps({
        'dated_records': len(dated_records), 'undated_records': undated,
        'plotted_modules': dict(running), 'counting_unit': 'unique reviewed module ID',
        'year_only_placement': 'January; date precision retained in ledger'
    }, indent=2)+'\n')
    plot_timeline(months, cumulative)


# Layer order follows the taxonomy (LLM side, then general to specific). Colours are the V7 kit's HUE dark
# shades (llm amber, gh blue, gts teal, tsk red); `MID` and `LIGHT` are the matching kit mid and light shades.
LAYERS = ["LLM-side", "General Harness", "General Time Series Harness", "Task-Specific Harness"]
COLORS = dict(zip(LAYERS, ["#C9861A", "#3B5BA5", "#23887C", "#C9503F"]))
MID = dict(zip(LAYERS, ["#F3C977", "#9FB3E1", "#8ACDC4", "#EFA396"]))
LABEL_INK = {name: "white" for name in LAYERS}
DISPLAY = {"LLM-side": "LLM-Side", "General Harness": "General Harness",
           "General Time Series Harness": "General Time Series Harness",
           "Task-Specific Harness": "Task-Specific Harness"}   # Title Case labels; data keys stay unchanged
INK, MUTED = "#1F2A44", "#5E6472"
ZONE_FILL, ZONE_LINE, GRID = "#F5F7FB", "#C9D2E3", "#DCE2EC"
FONT = "Comic Sans MS"
PERIODS = [("2023\u201324 H1", "2024-06"), ("2024 H2", "2024-12"), ("2025 H1", "2025-06"),
           ("2025 H2", "2025-12"), ("2026 H1", "2026-06"), ("2026 Q3", "2026-09"),
           ("2026 Q4", "2026-12")]
ORIGIN = datetime(2023, 8, 1)


def months_since_origin(dates):
    return np.array([(d - ORIGIN).days / 30.44 for d in dates])


def exponential(t, a, b):
    return a * np.exp(b * t)


def value_at(months: list[str], series: list[int], month: str) -> int:
    """Cumulative value at the end of ``month`` (last observation on or before it)."""
    value = 0
    for m, v in zip(months, series):
        if m <= month:
            value = v
    return value


def first_lasting_lead(leader, other):
    """First index from which ``leader`` stays strictly above ``other``."""
    for i in range(len(leader)):
        if all(a > b for a, b in zip(leader[i:], other[i:])):
            return i
    return None


FIG_W, FIG_H = 13.333, 6.45        # inches; the kit canvas width
ZONES = {"a": (0.12, 0.10, 6.88, 5.10), "b": (7.16, 0.10, 6.05, 5.10)}   # x, y, w, h in inches from bottom-left
AXES = {"a": (1.02, 0.80, 5.36, 3.98), "b": (8.16, 1.12, 4.92, 3.48)}
TITLES = {"a": "(a)  Cumulative Module Contributions", "b": "(b)  Share of New Modules by Period"}


def zone_panel(fig, key):
    """Pale tinted panel with a dashed outline and a dark pill title on its top edge (as kit zone())."""
    x, y, w, h = ZONES[key]
    fig.patches.append(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0,rounding_size=0.16",
                                      transform=fig.dpi_scale_trans, fc=ZONE_FILL, ec=ZONE_LINE, lw=1.1,
                                      ls=(0, (5, 3)), zorder=-5))
    t = fig.text(x + w / 2, y + h, f"  {TITLES[key]}  ", transform=fig.dpi_scale_trans, ha="center", va="center",
                 fontsize=16.5, fontweight="bold", color="white", zorder=5,
                 bbox=dict(boxstyle="round,pad=0.42,rounding_size=0.86", fc=INK, ec="none"))
    t.get_bbox_patch().set_path_effects([pe.SimplePatchShadow(offset=(1.6, -2.2), shadow_rgbFace="#3A3020", alpha=0.3),
                                         pe.Normal()])


def add_axes(fig, key):
    x, y, w, h = AXES[key]
    ax = fig.add_axes((x / FIG_W, y / FIG_H, w / FIG_W, h / FIG_H))
    ax.set_facecolor("none")
    ax.spines[["top", "right", "left"]].set_visible(False)
    ax.spines["bottom"].set_color(MUTED)
    ax.spines["bottom"].set_linewidth(1.1)
    ax.grid(axis="y", color=GRID, lw=1.0, zorder=0)
    ax.set_axisbelow(True)
    ax.tick_params(axis="y", length=0, pad=6)
    ax.tick_params(axis="x", length=5, width=1.0, color=MUTED, pad=5)
    return ax


def plot_timeline(months: list[str], cumulative: dict[str, list[int]]) -> None:
    plt.rcParams.update({
        "font.family": FONT, "font.size": 13.5, "axes.labelsize": 14,
        "xtick.labelsize": 13, "ytick.labelsize": 13, "axes.edgecolor": MUTED,
        "xtick.direction": "out", "ytick.direction": "out", "axes.labelweight": "bold",
        "axes.labelcolor": INK, "xtick.color": MUTED, "ytick.color": MUTED, "pdf.fonttype": 42,
    })
    dates = [datetime.strptime(month, "%Y-%m") for month in months]
    t = months_since_origin(dates)
    grid_t = np.linspace(t[0], t[-1], 200)
    grid_dates = [ORIGIN + timedelta(days=float(x) * 30.44) for x in grid_t]

    fig = plt.figure(figsize=(FIG_W, FIG_H))
    for key in ZONES:
        zone_panel(fig, key)
    ax, bx = add_axes(fig, "a"), add_axes(fig, "b")

    # (a) Observed cumulative counts as light points; least-squares exponential
    # fit as the expectation, with a band of one residual standard deviation.
    legend_labels = []
    for name in LAYERS:
        y = np.asarray(cumulative[name], dtype=float)
        (a, b), _ = curve_fit(exponential, t, y, p0=(2.0, 0.1), maxfev=20000)
        sd = np.std(y - exponential(t, a, b), ddof=2)
        fit = exponential(grid_t, a, b)
        color = COLORS[name]
        ax.fill_between(grid_dates, np.clip(fit - sd, 0, None), fit + sd, color=color, alpha=0.14, lw=0, zorder=1)
        ax.scatter(dates, y, s=40, color=color, alpha=0.5, lw=0, zorder=2)
        ax.plot(grid_dates, fit, color=color, lw=2.8, solid_capstyle="round", zorder=3)
        legend_labels.append(f"{DISPLAY[name]} (doubling {np.log(2) / b:.1f} mo)")
    # End values, nudged apart so that close series stay legible.
    placed = []
    for name in sorted(LAYERS, key=lambda n: cumulative[n][-1]):
        value = cumulative[name][-1]
        y_text = max(value, placed[-1] + 12) if placed else value
        placed.append(y_text)
        ax.annotate(f"{value}", (dates[-1], value), xytext=(dates[-1] + timedelta(days=16), y_text),
                    va="center", fontsize=14, fontweight="bold", color=COLORS[name], annotation_clip=False)
    callouts = [("Task-Specific Harness", "Task-Specific Harness\nleads LLM side", (-150, 62)),
                ("General Harness", "General Harness\nleads LLM side", (-205, 92))]
    for leader, text, offset in callouts:
        i = first_lasting_lead(cumulative[leader], cumulative["LLM-side"])
        if i is None:
            continue
        point = (dates[i], cumulative[leader][i])
        ax.plot(*point, "o", ms=12, mfc="white", mec=INK, mew=1.8, zorder=5)
        ax.annotate(f"{text} ({dates[i]:%b %Y})", point, xytext=offset, textcoords="offset points",
                    fontsize=13, color=COLORS[leader], fontweight="bold", ha="left", va="bottom", zorder=6,
                    bbox=dict(boxstyle="round,pad=0.38,rounding_size=0.5", fc="white", ec=MID[leader], lw=1.2),
                    arrowprops=dict(arrowstyle="-", color=COLORS[leader], lw=1.3, shrinkA=0, shrinkB=7))
    ax.set_ylabel("Cumulative Modules", labelpad=8)
    ax.set_ylim(0, 210)
    ax.set_yticks([0, 50, 100, 150, 200])
    ax.set_xlim(dates[0] - timedelta(days=20), datetime(2026, 12, 15))
    ax.xaxis.set_major_locator(mdates.YearLocator())
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%Y"))

    # (b) Share of newly published modules per period, every segment labelled.
    previous = {name: 0 for name in LAYERS}
    for x, (label, end) in enumerate(PERIODS):
        current = {name: value_at(months, cumulative[name], end) for name in LAYERS}
        new = {name: current[name] - previous[name] for name in LAYERS}
        total = sum(new.values())
        bottom = 0.0
        for name in LAYERS:
            share = 100 * new[name] / total
            bx.bar(x, share, bottom=bottom, width=0.74, color=COLORS[name], edgecolor="white", linewidth=1.4, zorder=3)
            if share >= 4:
                bx.text(x, bottom + share / 2, f"{share:.0f}%", ha="center", va="center",
                        fontsize=12 if share >= 7 else 11.5, fontweight="bold", color=LABEL_INK[name], zorder=4)
            bottom += share
        bx.text(x, 101.5, f"n={total}", ha="center", va="bottom", fontsize=12.5, color=INK)
        previous = current
    bx.set_xticks(range(len(PERIODS)), [label.replace(" ", "\n", 1) for label, _ in PERIODS], fontsize=12.5)
    bx.set_xlim(-0.55, len(PERIODS) - 0.45)
    bx.set_ylim(0, 108)
    bx.set_yticks([0, 25, 50, 75, 100], ["0", "25", "50", "75", "100%"])
    bx.set_ylabel("Share of New Modules", labelpad=8)

    handles = [plt.Line2D([], [], color=COLORS[n], lw=3.2, marker="o", ms=7.5, mfc=COLORS[n], mec="none") for n in LAYERS]
    fig.legend(handles, legend_labels, loc="center", ncol=2, frameon=False, fontsize=14,
               bbox_to_anchor=(0.5, 5.92 / FIG_H), handlelength=2.0, columnspacing=3.0, labelspacing=0.45)
    fig.savefig(OUT_PNG, dpi=110)
    fig.savefig(OUT_PDF)
    plt.close(fig)

if __name__ == "__main__":
    main()
