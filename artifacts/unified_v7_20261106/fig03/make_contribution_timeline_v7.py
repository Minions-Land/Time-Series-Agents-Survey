def count_module_labels(value: dict) -> int:
    """Count concrete module labels in one exclusive ledger view.

    ``module_level_contributions`` is generated by the classification manager
    after applying the deepest-applicable-layer rule. Counting its labels
    keeps the plot at module level without promoting a task-bound component
    back into GTS or GH.
    """
    dimensions = value.get("dimensions", value) if isinstance(value, dict) else {}
    return len({label for labels in dimensions.values() if isinstance(labels, list) for label in labels})


def in_scope(record: dict) -> bool:
    """Schema 3.0: only reviewed contributions count; background references are excluded."""
    module = record.get("module_level_contributions", {})
    return (record.get("inclusion") == "reviewed_contribution" and "modules" in module
            and module.get("review_status") in {"paper_verified", "repository_verified"})


def contribution_counts(record: dict) -> dict[str, int]:
    module = record.get("module_level_contributions", {})
    if in_scope(record):
        counts = Counter(m["layer"] for m in module["modules"])
        return {"LLM-side": counts["LLM"], "General Harness": counts["GH"],
                "General Time Series Harness": counts["GTS"], "Task-Specific Harness": counts["TSK"]}
    return {name: 0 for name in ("LLM-side", "General Harness", "General Time Series Harness", "Task-Specific Harness")}


def main() -> None:
    records = json.loads(LEDGER.read_text(encoding="utf-8"))
    # panel (c) needs no date, so it covers every reviewed work
    for record in records:
        if not in_scope(record):
            continue
        for module in record["module_level_contributions"]["modules"]:
            layer = module["layer"]
            if layer not in HARNESS:
                continue
            LAYER_MODULES[layer] += 1
            DIM_LINKS.extend((d, layer) for d in module.get("dimensions") or [] if d in DIMENSIONS)
            GROUP_LINKS.extend((layer, g) for g in GROUP_ORDER if g in module_groups(module))
            PAIRS.extend((d, g, layer) for d in module.get("dimensions") or [] if d in DIMENSIONS
                         for g in GROUP_ORDER if g in module_groups(module))
    monthly: dict[str, Counter] = {}
    dated_records, undated = [], []
    for record in records:
        counts = contribution_counts(record)
        if not sum(counts.values()):
            continue
        month = record.get("publication", {}).get("public_month") or ""
        if not (len(month) == 7 and month[4] == "-" and month[:4].isdigit() and month[5:].isdigit()):
            month = None                                # malformed or missing: reported, never guessed
        if not month:
            undated.append(record["citation"]["key"])
            continue
        dated_records.append(record["citation"]["key"])
        monthly.setdefault(month, Counter()).update(counts)

    months = sorted(monthly)
    running = Counter()
    rows = []
    cumulative = {name: [] for name in contribution_counts(records[0])}
    for month in months:
        running.update(monthly[month])
        row = {"public_month": month}
        for name in cumulative:
            cumulative[name].append(running[name])
            row[name] = running[name]
        rows.append(row)

    OUT_CSV.write_text("", encoding="utf-8")
    with OUT_CSV.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["public_month", *cumulative], lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)

    OUT_COVERAGE.write_text(json.dumps({
        'dated_records': len(dated_records), 'undated_records': undated,
        'plotted_modules': dict(running), 'counting_unit': 'unique reviewed module ID',
    }, indent=2)+'\n')
    with OUT_MECHANISM.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["mechanism dimension", *HARNESS])
        for dimension in DIMENSIONS:
            writer.writerow([dimension, *(DIM_LINKS.count((dimension, layer)) for layer in HARNESS)])
    with OUT_GROUPS.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["task group", *HARNESS])
        for g in GROUP_ORDER:
            writer.writerow([GROUPS[g], *(GROUP_LINKS.count((layer, g)) for layer in HARNESS)])
        writer.writerow(["Harness modules", *(LAYER_MODULES[layer] for layer in HARNESS)])
    plot_timeline(months, cumulative)
    coverage = json.loads(OUT_COVERAGE.read_text())
    coverage["calibration"] = STATS                       # every number the caption and text quote from (a) and (b)
    OUT_COVERAGE.write_text(json.dumps(coverage, indent=2) + "\n")


